"""Consolidate source-check receipts without merging uncertain report identities."""
from __future__ import annotations

from collections import Counter, defaultdict
from hashlib import sha256
import json
from pathlib import Path
import re
from urllib.parse import urlsplit

from build_other_landing_inventory import likely_key


ROOT = Path(__file__).resolve().parents[1]
QA = ROOT / "docs/qa/landing-sites-other-20261103"
ACCESS = {"original_reviewed", "catalog_reviewed", "citation_only", "unresolved"}
GEOMETRY = {"diagram", "description", "insufficient"}


def load_asset(name):
    path = ROOT / name
    raw = path.read_bytes()
    text = raw.decode("utf-8")
    start = re.search(r'\{\s*"source"\s*:', text)
    if not start:
        raise ValueError(f"Missing catalog source payload in {name}")
    payload, _ = json.JSONDecoder().raw_decode(text[start.start():])
    return payload["rows"], sha256(raw).hexdigest()


def build():
    rows_by_id = {}
    groups = defaultdict(list)
    pins = {}
    for name in ("landing_site_other_catalog.js", "landing_site_australian_catalog.js"):
        rows, pins[name] = load_asset(name)
        for row in rows:
            ident = row["id"]
            if ident in rows_by_id:
                raise ValueError(f"Duplicate inventory ID {ident}")
            rows_by_id[ident] = row
            key = likely_key(row.get("date"), row.get("location"))
            if key and key[1]:
                groups[key].append(ident)
    phillips, pins["landing_site_phillips_catalog.js"] = load_asset("landing_site_phillips_catalog.js")
    for row in phillips:
        key = likely_key(row.get("date"), row.get("location"))
        if key and key[1]:
            groups[key].append("Phillips #" + str(row["id"]))

    receipts = {}
    for name in ("direct.json", "australian.json", "historical.json", "ufocat.json"):
        path = QA / name
        raw = path.read_bytes()
        pins[name] = sha256(raw).hexdigest()
        for row in json.loads(raw):
            ident = row["id"]
            if ident not in rows_by_id or ident in receipts:
                raise ValueError(f"Unexpected or repeated review ID {ident} in {name}")
            if row["access"] not in ACCESS or row["geometry"] not in GEOMETRY:
                raise ValueError(f"Unknown review disposition for {ident}")
            if row.get("url") and urlsplit(row["url"]).scheme != "https":
                raise ValueError(f"Unexpected source URL for {ident}")
            if row["geometry"] == "diagram" and not row.get("caseId"):
                raise ValueError(f"A diagram needs an exact dossier link: {ident}")
            receipts[ident] = row
    missing = rows_by_id.keys() - receipts.keys()
    if missing:
        raise ValueError(f"Missing {len(missing)} review dispositions: {sorted(missing)[:5]}")

    related = {}
    for peers in groups.values():
        if len(peers) > 1:
            for ident in peers:
                if ident in receipts:
                    related[ident] = [peer for peer in peers if peer != ident]

    linked = Counter(row["caseId"] for row in receipts.values() if row.get("caseId"))
    output = {}
    for ident, row in sorted(receipts.items()):
        out = {key: row[key] for key in ("access", "geometry", "caseId", "url", "locator", "note") if row.get(key)}
        if row.get("caseId") and linked[row["caseId"]] > 1:
            out["sharedCaseRecords"] = linked[row["caseId"]]
        if ident in related:
            out["possibleMatches"] = related[ident]
        output[ident] = out

    return {
        "records": output,
        "counts": {
            "access": dict(Counter(row["access"] for row in receipts.values())),
            "geometry": dict(Counter(row["geometry"] for row in receipts.values())),
            "linkedRecords": sum(linked.values()),
            "linkedCases": len(linked),
            "sharedDossiers": sum(count > 1 for count in linked.values()),
            "possibleOverlapRecords": len(related),
        },
        "inputPins": pins,
    }


if __name__ == "__main__":
    payload = build()
    data = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    (ROOT / "landing_site_review_audit.js").write_text(
        "// Generated by scripts/build_landing_site_review_audit.py from checked source dispositions.\n"
        "(function (root, audit) {\n"
        '  if (typeof module === "object" && module.exports) module.exports = audit;\n'
        "  root.UfoLandingSiteReviewAudit = audit;\n"
        f"}})(globalThis, {data});\n", encoding="utf-8", newline="\n")
    print(json.dumps(payload["counts"], ensure_ascii=False, sort_keys=True))
